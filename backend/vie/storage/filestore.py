"""Content-addressed file storage on the `vie_files` volume.

Paths are always generated by the system (SHA-256 / UUIDs); user-supplied file
names are only kept as sanitised metadata. Every resolved path is checked to stay
inside the data directory (defence in depth against path traversal).
"""

from __future__ import annotations

import hashlib
import os
import re
import shutil
import uuid
from pathlib import Path

from ..core.config import get_settings
from ..core.errors import Forbidden

EXT_BY_MIME = {"image/png": "png", "image/jpeg": "jpg", "image/webp": "webp", "application/pdf": "pdf",
               "video/mp4": "mp4", "video/webm": "webm", "video/quicktime": "mov"}


class FileStore:
    def __init__(self, root: Path | None = None):
        self.root = (root or get_settings().data_dir).resolve()

    def ensure_dirs(self) -> None:
        for sub in ("originals", "derived", "staging", "exports"):
            (self.root / sub).mkdir(parents=True, exist_ok=True)

    # -- path safety -------------------------------------------------------------
    def resolve(self, rel: str) -> Path:
        if not rel or rel.startswith("/") or "\x00" in rel:
            raise Forbidden("invalid_path", "Ruta de archivo no válida.")
        path = (self.root / rel).resolve()
        if not path.is_relative_to(self.root):
            raise Forbidden("invalid_path", "Ruta de archivo no válida.")
        return path

    @staticmethod
    def sanitize_filename(name: str | None, max_len: int = 120) -> str:
        """Display-only name: strips directories, control and reserved characters."""
        base = os.path.basename((name or "").replace("\\", "/"))
        base = re.sub(r"[\x00-\x1f\x7f<>:\"|?*]", "_", base).strip(" .")
        return (base or "archivo")[:max_len]

    # -- writes --------------------------------------------------------------------
    def _atomic_write(self, path: Path, data: bytes) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(f".{path.name}.{uuid.uuid4().hex}.tmp")
        with open(tmp, "wb") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)

    def save_original(self, data: bytes, mime: str) -> tuple[str, str, int]:
        sha = hashlib.sha256(data).hexdigest()
        rel = f"originals/{sha[:2]}/{sha}.{EXT_BY_MIME.get(mime, 'bin')}"
        path = self.resolve(rel)
        if not path.exists():
            self._atomic_write(path, data)
            os.chmod(path, 0o440)  # originals are immutable
        return rel, sha, len(data)

    def save_derived(self, observation_id: str, name: str, data: bytes) -> tuple[str, str, int]:
        if not re.fullmatch(r"[a-z0-9_]+\.(jpg|png|json)", name):
            raise ValueError("invalid derived name")
        rel = f"derived/{observation_id}/{name}"
        self._atomic_write(self.resolve(rel), data)
        return rel, hashlib.sha256(data).hexdigest(), len(data)

    def read(self, rel: str) -> bytes:
        return self.resolve(rel).read_bytes()

    # -- deletes (only called after an explicit, confirmed user action) -----------
    def delete_derived(self, observation_id: str) -> None:
        d = self.resolve(f"derived/{observation_id}")
        if d.exists() and d.is_dir():
            shutil.rmtree(d)

    def delete_original(self, rel: str) -> None:
        p = self.resolve(rel)
        if p.exists():
            os.chmod(p, 0o640)
            p.unlink()

    # -- stats -------------------------------------------------------------------------
    def usage(self) -> dict[str, int]:
        out = {}
        for sub in ("originals", "derived", "staging", "exports"):
            total = 0
            base = self.root / sub
            if base.exists():
                for p in base.rglob("*"):
                    if p.is_file():
                        total += p.stat().st_size
            out[sub] = total
        out["total"] = sum(out.values())
        return out


_store: FileStore | None = None


def get_store() -> FileStore:
    global _store
    if _store is None:
        _store = FileStore()
    return _store
